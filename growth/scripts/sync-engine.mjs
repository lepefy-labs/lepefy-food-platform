// Copies the growth engine (single source of truth: growth/src and growth/config)
// into the storefront, which re-validates every dossier on import and lints the
// messages edited in the admin page. The storefront never re-implements it.
//   node growth/scripts/sync-engine.mjs          write
//   node growth/scripts/sync-engine.mjs --check  fail if the copy is stale
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, '..');
const DEST = join(ROOT, '..', 'apps', 'storefront', 'src', 'lib', 'growth', 'engine');
const HEADER = '// GENERATED by growth/scripts/sync-engine.mjs from growth/src. Do not edit: change growth/src and re-run it.\n';

const FILES = [
  ['src/identity.mjs', 'identity.mjs', (s) => HEADER + s],
  ['src/qualify.mjs', 'qualify.mjs', (s) => HEADER + s],
  ['config/features.json', 'features.json', (s) => s],
];

// Line endings are not content: a Windows checkout (core.autocrlf) turns the
// sources and the copy into CRLF, but the header added here ends with LF.
const sameContent = (a, b) => a !== null && a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n');

const check = process.argv.includes('--check');
let stale = 0;
mkdirSync(DEST, { recursive: true });
for (const [from, to, transform] of FILES) {
  const out = transform(readFileSync(join(ROOT, from), 'utf8'));
  const target = join(DEST, to);
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (sameContent(current, out)) continue;
  if (check) { console.error(`stale: ${to}`); stale++; } else writeFileSync(target, out);
}
if (check && stale) process.exit(1);
if (!check) console.log(`Motore copiato in ${DEST}`);
