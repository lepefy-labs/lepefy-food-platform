  actor_type     text not null check (actor_type in ('tenant', 'lepefy', 'system')),
  actor_admin_id uuid references public.admin_users(id) on delete set null,
  from_value     text check (from_value is null or char_length(from_value) <= 200),
  to_value       text check (to_value is null or char_length(to_value) <= 200),
  -- false : jamais renvoyé à la boutique (priorité, assignation, liens, visibilité…).
  public         boolean not null default false,
  created_at     timestamptz not null default now(),
  constraint support_events_ticket_fk foreign key (tenant_id, ticket_id)
    references public.support_tickets (tenant_id, id) on delete cascade
);

create index if not exists support_events_ticket_created_idx on public.support_events (ticket_id, created_at);

-- ─── 5. Lecture par admin (multi-utilisateur) ────────────────────────────────
