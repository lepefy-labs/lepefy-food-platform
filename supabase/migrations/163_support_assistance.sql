-- 163 — Assistance & suggestions (docs/SMART_ASSISTANCE.md)
--
-- Demandes d'assistance des boutiques vers Lepefy : une demande = un fil de
-- messages persistant, des captures privées, un historique et un état de
-- lecture par admin. Le module est derrière le flag de release
-- `support_assistance` (tenant_feature_flags, aucune ligne = éteint).
--
-- Règles :
-- * RLS forcée sans policy, aucun privilège pour anon/authenticated : les tables
--   ne sont lues que côté serveur (service role) et ne sont modifiées que par les
--   RPC security definer ci-dessous, appelées par les API autorisées.
-- * La boutique ne lit que par `support_tenant_ticket_page` et
--   `support_tenant_thread`, qui ne renvoient jamais les notes internes, les
--   pièces internes, les liens GitHub, la priorité, l'assignation ni les
--   évènements privés.
-- * Le tenant d'une écriture boutique est toujours passé par le serveur
--   (`getTenant()`), jamais par le navigateur ; chaque RPC le vérifie contre la
--   demande.
-- * Commandes sensibles idempotentes (`client_key`), limites anti-abus en SQL.
-- * Additive et réversible : rollback en fin de fichier.

begin;

-- ─── 1. Demandes ─────────────────────────────────────────────────────────────
create table if not exists public.support_tickets (
  id                     uuid primary key default gen_random_uuid(),
  number                 bigint generated by default as identity (start with 1001) unique,
  tenant_id              uuid not null references public.tenants(id) on delete cascade,
  origin                 text not null default 'tenant_app' check (origin in ('tenant_app', 'platform_manual')),
  source_channel         text not null default 'app' check (source_channel in ('app', 'whatsapp', 'phone', 'email', 'internal')),
  external_reference     text check (external_reference is null or char_length(external_reference) <= 200),
  requester_admin_id     uuid references public.admin_users(id) on delete set null,
  requester_label        text check (requester_label is null or char_length(requester_label) <= 120),
  created_by_admin_id    uuid references public.admin_users(id) on delete set null,
  title                  text not null check (char_length(btrim(title)) between 1 and 140),
  summary                text not null default '' check (char_length(summary) <= 600),
  category               text not null default 'unspecified' check (category in ('unspecified', 'problem', 'improvement', 'question')),
  status                 text not null default 'new' check (status in ('new', 'triaged', 'planned', 'in_progress', 'waiting_tenant', 'resolved', 'closed')),
  priority               text not null default 'normal' check (priority in ('low', 'normal', 'high', 'critical')),
  declared_urgent        boolean not null default false,
  assignee_admin_id      uuid references public.admin_users(id) on delete set null,
  visible_to_tenant      boolean not null default true,
  context                jsonb not null default '{}'::jsonb
                         check (jsonb_typeof(context) = 'object' and octet_length(context::text) <= 2000),
  resource_type          text check (resource_type in ('order', 'product', 'customer')),
  resource_id            uuid,
  resource_label         text check (resource_label is null or char_length(resource_label) <= 120),
  merged_into_ticket_id  uuid references public.support_tickets(id) on delete set null,
  tenant_feedback        text check (tenant_feedback in ('solved', 'not_solved')),
  tenant_feedback_at     timestamptz,
  client_key             uuid,
  reported_at            timestamptz not null default now(),
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),
  last_activity_at       timestamptz not null default now(),
  -- Dernier message de la boutique (ou date de la demande saisie par Lepefy).
  last_tenant_message_at timestamptz,
  -- Dernière réponse publique de Lepefy.
  last_staff_reply_at    timestamptz,
  -- Dernière nouveauté visible par la boutique (réponse, statut affiché) : sert aux « non lus ».
  last_public_update_at  timestamptz not null default now(),
  first_response_at      timestamptz,
  resolved_at            timestamptz,
  closed_at              timestamptz,
  reopened_at            timestamptz,
  reopen_count           integer not null default 0 check (reopen_count >= 0),
  search_document        tsvector generated always as (
                           to_tsvector('french'::regconfig, coalesce(title, '') || ' ' || coalesce(summary, ''))
                         ) stored,
  constraint support_tickets_tenant_id_key unique (tenant_id, id),
  constraint support_tickets_client_key unique (tenant_id, client_key),
  constraint support_tickets_resource_pair check ((resource_type is null) = (resource_id is null)),
  constraint support_tickets_merge_not_self check (merged_into_ticket_id is null or merged_into_ticket_id <> id),
  constraint support_tickets_feedback_pair check ((tenant_feedback is null) = (tenant_feedback_at is null)),
  -- Une demande saisie par Lepefy vient toujours d'un autre canal que l'application.
  constraint support_tickets_manual_channel check (origin = 'tenant_app' or source_channel <> 'app'),
  constraint support_tickets_app_channel check (origin = 'platform_manual' or source_channel = 'app')
);

create index if not exists support_tickets_tenant_activity_idx on public.support_tickets (tenant_id, last_activity_at desc);
create index if not exists support_tickets_status_activity_idx on public.support_tickets (status, last_activity_at desc);
create index if not exists support_tickets_requester_created_idx on public.support_tickets (requester_admin_id, created_at desc) where requester_admin_id is not null;
create index if not exists support_tickets_assignee_idx on public.support_tickets (assignee_admin_id) where assignee_admin_id is not null;
create index if not exists support_tickets_search_idx on public.support_tickets using gin (search_document);

-- ─── 2. Messages ─────────────────────────────────────────────────────────────
create table if not exists public.support_messages (
  id               uuid primary key default gen_random_uuid(),
  tenant_id        uuid not null,
  ticket_id        uuid not null,
  author_type      text not null check (author_type in ('tenant', 'lepefy')),
  author_admin_id  uuid references public.admin_users(id) on delete set null,
  author_label     text check (author_label is null or char_length(author_label) <= 120),
  kind             text not null default 'message' check (kind in ('message', 'internal_note')),
  body             text not null check (char_length(btrim(body)) between 1 and 5000),
  -- Message reçu ailleurs (WhatsApp, téléphone…) et saisi par Lepefy : jamais attribué à la boutique.
  relayed_from     text check (relayed_from in ('whatsapp', 'phone', 'email', 'internal')),
  original_sent_at timestamptz,
  client_key       uuid,
  created_at       timestamptz not null default now(),
  constraint support_messages_tenant_id_key unique (tenant_id, id),
  constraint support_messages_client_key unique (ticket_id, client_key),
  constraint support_messages_ticket_fk foreign key (tenant_id, ticket_id)
    references public.support_tickets (tenant_id, id) on delete cascade,
  constraint support_messages_internal_staff check (kind = 'message' or author_type = 'lepefy'),
  constraint support_messages_relay_staff check (relayed_from is null or author_type = 'lepefy')
);

create index if not exists support_messages_ticket_created_idx on public.support_messages (ticket_id, created_at);
create index if not exists support_messages_author_created_idx on public.support_messages (author_admin_id, created_at desc) where author_admin_id is not null;

-- ─── 3. Pièces jointes (bucket privé) ────────────────────────────────────────
create table if not exists public.support_attachments (
  id                   uuid primary key default gen_random_uuid(),
  tenant_id            uuid not null references public.tenants(id) on delete cascade,
  ticket_id            uuid,
  message_id           uuid,
  uploaded_by_admin_id uuid references public.admin_users(id) on delete set null,
  uploader_type        text not null check (uploader_type in ('tenant', 'lepefy')),
  storage_path         text not null unique check (storage_path ~ '^[0-9a-f-]{36}/[0-9a-f-]{36}\.(jpg|png|webp)$'),
  mime_type            text not null check (mime_type in ('image/jpeg', 'image/png', 'image/webp')),
  size_bytes           integer not null check (size_bytes > 0 and size_bytes <= 5242880),
  width                integer check (width is null or width > 0),
  height               integer check (height is null or height > 0),
  internal             boolean not null default false,
  created_at           timestamptz not null default now(),
  attached_at          timestamptz,
  constraint support_attachments_ticket_fk foreign key (tenant_id, ticket_id)
    references public.support_tickets (tenant_id, id) on delete cascade,
  constraint support_attachments_message_fk foreign key (tenant_id, message_id)
    references public.support_messages (tenant_id, id) on delete cascade,
  constraint support_attachments_attached_pair check ((message_id is null) = (attached_at is null)),
  constraint support_attachments_message_has_ticket check (message_id is null or ticket_id is not null)
);

create index if not exists support_attachments_message_idx on public.support_attachments (message_id) where message_id is not null;
create index if not exists support_attachments_staged_idx on public.support_attachments (uploaded_by_admin_id, created_at) where message_id is null;

-- ─── 4. Historique ───────────────────────────────────────────────────────────
create table if not exists public.support_events (
  id             uuid primary key default gen_random_uuid(),
  tenant_id      uuid not null,
  ticket_id      uuid not null,
  event_type     text not null check (event_type in (
                   'created', 'imported', 'status_changed', 'priority_changed', 'assigned', 'category_changed',
                   'visibility_changed', 'title_changed', 'merged_into', 'merged_from', 'link_added', 'link_removed',
