-- ─── 7. RLS et privilèges ────────────────────────────────────────────────────
do $$
declare t text;
begin
  foreach t in array array['support_tickets', 'support_messages', 'support_attachments', 'support_events', 'support_read_states', 'support_links'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('alter table public.%I force row level security', t);
    -- Les privilèges par défaut de Supabase donnent tout au service role : il ne garde que la lecture.
    execute format('revoke all on public.%I from public, anon, authenticated, service_role', t);
    execute format('grant select on public.%I to service_role', t);
  end loop;
end $$;
-- Téléversement d'une capture avant l'envoi (ligne « en attente ») et nettoyage des captures non envoyées.
grant insert, delete on public.support_attachments to service_role;

-- ─── 8. Stockage privé ───────────────────────────────────────────────────────
-- Aucune policy storage : lecture par la route autorisée puis URL signée de 60 s.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('support-attachments', 'support-attachments', false, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set
  public = false,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- ─── 9. Règles partagées (miroir de lib/support/rules.ts) ────────────────────
create or replace function public.support_tenant_status(p_status text)
returns text language sql immutable as $$
  select case
    when p_status = 'new' then 'sent'
    when p_status in ('triaged', 'planned', 'in_progress') then 'in_progress'
    when p_status = 'waiting_tenant' then 'waiting_you'
    when p_status in ('resolved', 'closed') then 'done'
    else 'in_progress'
  end
$$;

create or replace function public.support_transition_allowed(p_from text, p_to text)
returns boolean language sql immutable as $$
  select p_from <> p_to and case p_from
    when 'new'            then p_to in ('triaged', 'planned', 'in_progress', 'waiting_tenant', 'resolved', 'closed')
    when 'triaged'        then p_to in ('planned', 'in_progress', 'waiting_tenant', 'resolved', 'closed')
    when 'planned'        then p_to in ('triaged', 'in_progress', 'waiting_tenant', 'resolved', 'closed')
    when 'in_progress'    then p_to in ('planned', 'waiting_tenant', 'resolved', 'closed')
    when 'waiting_tenant' then p_to in ('triaged', 'in_progress', 'resolved', 'closed')
    when 'resolved'       then p_to in ('in_progress', 'closed')
    when 'closed'         then p_to in ('triaged')
    else false
  end
$$;

-- Captures « en attente » rattachées à un message : même tenant, même auteur, moins de 24 h, 5 au plus.
create or replace function public.support_attach_files(
  p_tenant_id uuid, p_ticket_id uuid, p_message_id uuid, p_actor_type text, p_actor_admin_id uuid,
  p_attachment_ids uuid[], p_internal boolean
) returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_ids uuid[] := coalesce((select array_agg(distinct x) from unnest(coalesce(p_attachment_ids, '{}'::uuid[])) as x where x is not null), '{}'::uuid[]);
  v_count integer;
begin
  if cardinality(v_ids) = 0 then return 0; end if;
  if cardinality(v_ids) > 5 then raise exception 'support_attachment_invalid'; end if;
  update public.support_attachments a
     set ticket_id = p_ticket_id, message_id = p_message_id, attached_at = now(), internal = p_internal
   where a.id = any(v_ids)
     and a.tenant_id = p_tenant_id
     and a.message_id is null
     and a.uploader_type = p_actor_type
     and a.uploaded_by_admin_id is not distinct from p_actor_admin_id
     and a.created_at > now() - interval '24 hours';
  get diagnostics v_count = row_count;
  if v_count <> cardinality(v_ids) then raise exception 'support_attachment_invalid'; end if;
  return v_count;
end $$;

-- ─── 10. Créer une demande ───────────────────────────────────────────────────
create or replace function public.support_create_ticket(
  p_tenant_id          uuid,
  p_actor_type         text,
  p_actor_admin_id     uuid,
  p_actor_label        text,
  p_title              text,
  p_body               text,
  p_category           text default 'unspecified',
  p_declared_urgent    boolean default false,
  p_priority           text default null,
  p_context            jsonb default '{}'::jsonb,
  p_resource_type      text default null,
  p_resource_id        uuid default null,
  p_resource_label     text default null,
  p_source_channel     text default 'app',
  p_external_reference text default null,
  p_reported_at        timestamptz default null,
  p_requester_label    text default null,
  p_visible            boolean default true,
  p_client_key         uuid default null,
  p_attachment_ids     uuid[] default null
)
returns table (out_ticket_id uuid, out_number bigint, out_created boolean)
language plpgsql security definer set search_path = public as $$
declare
  v_existing  public.support_tickets%rowtype;
  v_ticket    public.support_tickets%rowtype;
  v_message   uuid;
  v_body      text := btrim(coalesce(p_body, ''));
  v_title     text := left(btrim(coalesce(p_title, '')), 140);
  v_reported  timestamptz := least(coalesce(p_reported_at, now()), now());
  v_priority  text;
  v_manual    boolean := p_actor_type = 'lepefy';
begin
  if p_tenant_id is null or p_actor_type not in ('tenant', 'lepefy') or p_actor_admin_id is null then
    raise exception 'support_invalid_input';
  end if;
  if char_length(v_body) < 3 or char_length(v_body) > 5000 or char_length(v_title) < 1 then
    raise exception 'support_invalid_input';
  end if;
  if coalesce(p_category, 'unspecified') not in ('unspecified', 'problem', 'improvement', 'question') then
    raise exception 'support_invalid_input';
  end if;

  if p_client_key is not null then
    select * into v_existing from public.support_tickets where tenant_id = p_tenant_id and client_key = p_client_key;
    if found then
      return query select v_existing.id, v_existing.number, false;
      return;
    end if;
  end if;

  if not v_manual then
    -- 10 nouvelles demandes par heure et par admin au plus.
    if (select count(*) from public.support_tickets
         where requester_admin_id = p_actor_admin_id and created_at > now() - interval '1 hour') >= 10 then
      raise exception 'support_rate_limited';
    end if;
  else
    if coalesce(p_source_channel, 'app') not in ('whatsapp', 'phone', 'email', 'internal') then
      raise exception 'support_invalid_input';
    end if;
    if p_priority is not null and p_priority not in ('low', 'normal', 'high', 'critical') then
      raise exception 'support_invalid_input';
    end if;
  end if;

  -- Une urgence déclarée relève la priorité, sans jamais la rendre critique.
  v_priority := case
    when v_manual and p_priority is not null then p_priority
    when coalesce(p_declared_urgent, false) then 'high'
    else 'normal'
  end;

  insert into public.support_tickets (
    tenant_id, origin, source_channel, external_reference, requester_admin_id, requester_label, created_by_admin_id,
    title, summary, category, priority, declared_urgent, visible_to_tenant, context,
    resource_type, resource_id, resource_label, client_key, reported_at, last_tenant_message_at, last_public_update_at
  ) values (
    p_tenant_id,
    case when v_manual then 'platform_manual' else 'tenant_app' end,
    case when v_manual then p_source_channel else 'app' end,
    case when v_manual then nullif(left(btrim(coalesce(p_external_reference, '')), 200), '') else null end,
    case when v_manual then null else p_actor_admin_id end,
    nullif(left(btrim(coalesce(case when v_manual then p_requester_label else p_actor_label end, '')), 120), ''),
    p_actor_admin_id,
    v_title, left(v_body, 600), coalesce(p_category, 'unspecified'), v_priority, coalesce(p_declared_urgent, false),
    case when v_manual then coalesce(p_visible, true) else true end,
    coalesce(p_context, '{}'::jsonb),
    case when p_resource_id is null then null else p_resource_type end,
    case when p_resource_type is null then null else p_resource_id end,
    case when p_resource_id is null or p_resource_type is null then null else nullif(left(btrim(coalesce(p_resource_label, '')), 120), '') end,
    p_client_key,
    v_reported,
    v_reported,
    now()
  ) returning * into v_ticket;

  insert into public.support_messages (
    tenant_id, ticket_id, author_type, author_admin_id, author_label, kind, body, relayed_from, original_sent_at
  ) values (
    p_tenant_id, v_ticket.id, p_actor_type, p_actor_admin_id,
    nullif(left(btrim(coalesce(p_actor_label, '')), 120), ''),
    'message', v_body,
    case when v_manual then p_source_channel else null end,
    case when v_manual then v_reported else null end
  ) returning id into v_message;

  perform public.support_attach_files(p_tenant_id, v_ticket.id, v_message, p_actor_type, p_actor_admin_id, p_attachment_ids, false);

  insert into public.support_events (tenant_id, ticket_id, event_type, actor_type, actor_admin_id, to_value, public)
  values (p_tenant_id, v_ticket.id, case when v_manual then 'imported' else 'created' end, p_actor_type, p_actor_admin_id,
          v_ticket.source_channel, true);

  -- Le demandeur a « lu » sa propre demande.
  if not v_manual then
    insert into public.support_read_states (ticket_id, admin_id, tenant_id, side, last_read_at)
    values (v_ticket.id, p_actor_admin_id, p_tenant_id, 'tenant', clock_timestamp())
    on conflict (ticket_id, admin_id) do update set last_read_at = excluded.last_read_at;
  end if;

  perform public.audit_emit(false, p_tenant_id, 'support.ticket.created', 'support_ticket', v_ticket.id::text,
    'Demande n° ' || v_ticket.number, '[]'::jsonb,
    jsonb_build_object('origin', v_ticket.origin, 'source_channel', v_ticket.source_channel, 'category', v_ticket.category,
                       'declared_urgent', v_ticket.declared_urgent));

  return query select v_ticket.id, v_ticket.number, true;
end $$;

-- ─── 11. Ajouter un message (boutique, réponse Lepefy, note interne) ─────────
create or replace function public.support_post_message(
  p_ticket_id        uuid,
  p_tenant_id        uuid,
  p_actor_type       text,
  p_actor_admin_id   uuid,
  p_actor_label      text,
  p_kind             text,
  p_body             text,
  p_client_key       uuid default null,
  p_attachment_ids   uuid[] default null,
  p_wait_for_tenant  boolean default false
)
returns table (out_message_id uuid, out_created boolean, out_status text, out_reopened boolean)
language plpgsql security definer set search_path = public as $$
declare
  v_ticket   public.support_tickets%rowtype;
  v_existing uuid;
  v_message  uuid;
  v_body     text := btrim(coalesce(p_body, ''));
  v_kind     text := coalesce(p_kind, 'message');
  v_to       text;
  v_reopened boolean := false;
begin
  if p_ticket_id is null or p_actor_type not in ('tenant', 'lepefy') or p_actor_admin_id is null
     or v_kind not in ('message', 'internal_note') or char_length(v_body) < 1 or char_length(v_body) > 5000 then
    raise exception 'support_invalid_input';
  end if;
  if p_actor_type = 'tenant' and (p_tenant_id is null or v_kind <> 'message') then
    raise exception 'support_invalid_input';
  end if;

  select * into v_ticket from public.support_tickets where id = p_ticket_id for update;
  if not found or (p_actor_type = 'tenant' and (v_ticket.tenant_id <> p_tenant_id or not v_ticket.visible_to_tenant)) then
    raise exception 'support_ticket_not_found';
  end if;

  if p_client_key is not null then
    select id into v_existing from public.support_messages where ticket_id = p_ticket_id and client_key = p_client_key;
    if found then
      return query select v_existing, false, v_ticket.status, false;
      return;
    end if;
  end if;

  if p_actor_type = 'tenant' then
    if v_ticket.merged_into_ticket_id is not null then raise exception 'support_ticket_merged'; end if;
    if v_ticket.status = 'closed' then raise exception 'support_ticket_closed'; end if;
    -- 30 messages par 10 minutes et par admin au plus.
    if (select count(*) from public.support_messages
         where author_admin_id = p_actor_admin_id and author_type = 'tenant' and created_at > now() - interval '10 minutes') >= 30 then
      raise exception 'support_rate_limited';
    end if;
  end if;

  insert into public.support_messages (tenant_id, ticket_id, author_type, author_admin_id, author_label, kind, body, client_key)
  values (v_ticket.tenant_id, v_ticket.id, p_actor_type, p_actor_admin_id,
          nullif(left(btrim(coalesce(p_actor_label, '')), 120), ''), v_kind, v_body, p_client_key)
  returning id into v_message;

  perform public.support_attach_files(v_ticket.tenant_id, v_ticket.id, v_message, p_actor_type, p_actor_admin_id,
                                      p_attachment_ids, v_kind = 'internal_note');

  v_to := v_ticket.status;
  if p_actor_type = 'tenant' then
    if v_ticket.status = 'waiting_tenant' then
      v_to := 'in_progress';
    elsif v_ticket.status = 'resolved' then
      v_to := 'in_progress';
      v_reopened := true;
    end if;
    update public.support_tickets set
      status = v_to,
      last_tenant_message_at = now(),
      last_activity_at = now(),
      updated_at = now(),
      resolved_at = case when v_reopened then null else resolved_at end,
      reopened_at = case when v_reopened then now() else reopened_at end,
      reopen_count = reopen_count + case when v_reopened then 1 else 0 end
    where id = v_ticket.id;
  elsif v_kind = 'message' then
    if coalesce(p_wait_for_tenant, false) and v_ticket.status not in ('resolved', 'closed') then
      v_to := 'waiting_tenant';
    elsif v_ticket.status = 'new' then
      v_to := 'triaged';
    end if;
    update public.support_tickets set
      status = v_to,
      first_response_at = coalesce(first_response_at, now()),
      last_staff_reply_at = now(),
      last_public_update_at = clock_timestamp(),
      last_activity_at = now(),
      updated_at = now()
    where id = v_ticket.id;
  else
    update public.support_tickets set last_activity_at = now(), updated_at = now() where id = v_ticket.id;
  end if;

  if v_to <> v_ticket.status then
    insert into public.support_events (tenant_id, ticket_id, event_type, actor_type, actor_admin_id, from_value, to_value, public)
    values (v_ticket.tenant_id, v_ticket.id, case when v_reopened then 'reopened' else 'status_changed' end,
            case when p_actor_type = 'tenant' then 'tenant' else 'lepefy' end, p_actor_admin_id, v_ticket.status, v_to,
            public.support_tenant_status(v_ticket.status) <> public.support_tenant_status(v_to));
    perform public.audit_emit(false, v_ticket.tenant_id, 'support.ticket.status_changed', 'support_ticket', v_ticket.id::text,
      'Demande n° ' || v_ticket.number,
      jsonb_build_array(jsonb_build_object('field', 'status', 'before', v_ticket.status, 'after', v_to)),
      jsonb_build_object('reason', case when v_reopened then 'tenant_reopened' when p_actor_type = 'tenant' then 'tenant_message' else 'staff_reply' end));
  end if;

  return query select v_message, true, v_to, v_reopened;
end $$;

-- ─── 12. Statut (Lepefy) ─────────────────────────────────────────────────────
create or replace function public.support_set_status(
  p_ticket_id       uuid,
  p_actor_admin_id  uuid,
  p_to_status       text,
  p_expected_status text default null
)
returns table (out_status text, out_changed boolean)
language plpgsql security definer set search_path = public as $$
declare
  v_ticket public.support_tickets%rowtype;
  v_public boolean;
  v_reopen boolean;
begin
  if p_ticket_id is null or p_actor_admin_id is null then raise exception 'support_invalid_input'; end if;
  select * into v_ticket from public.support_tickets where id = p_ticket_id for update;
  if not found then raise exception 'support_ticket_not_found'; end if;
  if v_ticket.status = p_to_status then
    return query select v_ticket.status, false;
    return;
  end if;
  if p_expected_status is not null and v_ticket.status <> p_expected_status then raise exception 'support_status_conflict'; end if;
  if not public.support_transition_allowed(v_ticket.status, p_to_status) then raise exception 'support_transition_invalid'; end if;

  v_reopen := v_ticket.status in ('resolved', 'closed');
  v_public := public.support_tenant_status(v_ticket.status) <> public.support_tenant_status(p_to_status);

  update public.support_tickets set
    status = p_to_status,
    resolved_at = case when p_to_status = 'resolved' then now() when v_reopen then null else resolved_at end,
    closed_at = case when p_to_status = 'closed' then now() when v_reopen then null else closed_at end,
    reopened_at = case when v_reopen then now() else reopened_at end,
    reopen_count = reopen_count + case when v_reopen then 1 else 0 end,
    tenant_feedback = case when v_reopen then null else tenant_feedback end,
    tenant_feedback_at = case when v_reopen then null else tenant_feedback_at end,
    last_public_update_at = case when v_public then clock_timestamp() else last_public_update_at end,
    last_activity_at = now(),
    updated_at = now()
  where id = v_ticket.id;

  insert into public.support_events (tenant_id, ticket_id, event_type, actor_type, actor_admin_id, from_value, to_value, public)
  values (v_ticket.tenant_id, v_ticket.id, case when v_reopen then 'reopened' else 'status_changed' end, 'lepefy',
          p_actor_admin_id, v_ticket.status, p_to_status, v_public);

  perform public.audit_emit(false, v_ticket.tenant_id, 'support.ticket.status_changed', 'support_ticket', v_ticket.id::text,
    'Demande n° ' || v_ticket.number,
    jsonb_build_array(jsonb_build_object('field', 'status', 'before', v_ticket.status, 'after', p_to_status)), '{}'::jsonb);

  return query select p_to_status, true;
end $$;

-- ─── 13. Priorité, assignation, catégorie, titre, visibilité (Lepefy) ────────
create or replace function public.support_update_ticket(
  p_ticket_id       uuid,
  p_actor_admin_id  uuid,
  p_priority        text default null,
  p_assignee        uuid default null,
  p_clear_assignee  boolean default false,
  p_category        text default null,
  p_title           text default null,
  p_visible         boolean default null
)
returns table (out_changed integer)
language plpgsql security definer set search_path = public as $$
declare
  v_ticket  public.support_tickets%rowtype;
  v_changed integer := 0;
  v_title   text := nullif(left(btrim(coalesce(p_title, '')), 140), '');
begin
  if p_ticket_id is null or p_actor_admin_id is null then raise exception 'support_invalid_input'; end if;
  select * into v_ticket from public.support_tickets where id = p_ticket_id for update;
  if not found then raise exception 'support_ticket_not_found'; end if;

  if p_priority is not null and p_priority <> v_ticket.priority then
    if p_priority not in ('low', 'normal', 'high', 'critical') then raise exception 'support_invalid_input'; end if;
    update public.support_tickets set priority = p_priority where id = v_ticket.id;
    insert into public.support_events (tenant_id, ticket_id, event_type, actor_type, actor_admin_id, from_value, to_value)
    values (v_ticket.tenant_id, v_ticket.id, 'priority_changed', 'lepefy', p_actor_admin_id, v_ticket.priority, p_priority);
    perform public.audit_emit(false, v_ticket.tenant_id, 'support.ticket.priority_changed', 'support_ticket', v_ticket.id::text,
      'Demande n° ' || v_ticket.number,
      jsonb_build_array(jsonb_build_object('field', 'priority', 'before', v_ticket.priority, 'after', p_priority)), '{}'::jsonb);
    v_changed := v_changed + 1;
  end if;

  if (p_clear_assignee and v_ticket.assignee_admin_id is not null)
     or (p_assignee is not null and p_assignee is distinct from v_ticket.assignee_admin_id) then
    if p_assignee is not null and not exists (
      select 1 from public.admin_users where id = p_assignee and role = 'platform_owner' and active
    ) then
      raise exception 'support_assignee_invalid';
    end if;
    update public.support_tickets set assignee_admin_id = case when p_clear_assignee then null else p_assignee end where id = v_ticket.id;
    insert into public.support_events (tenant_id, ticket_id, event_type, actor_type, actor_admin_id, from_value, to_value)
    values (v_ticket.tenant_id, v_ticket.id, 'assigned', 'lepefy', p_actor_admin_id,
            v_ticket.assignee_admin_id::text, case when p_clear_assignee then null else p_assignee::text end);
    perform public.audit_emit(false, v_ticket.tenant_id, 'support.ticket.assigned', 'support_ticket', v_ticket.id::text,
      'Demande n° ' || v_ticket.number, '[]'::jsonb,
      jsonb_build_object('assigned', not p_clear_assignee));
    v_changed := v_changed + 1;
  end if;

  if p_category is not null and p_category <> v_ticket.category then
    if p_category not in ('unspecified', 'problem', 'improvement', 'question') then raise exception 'support_invalid_input'; end if;
    update public.support_tickets set category = p_category where id = v_ticket.id;
    insert into public.support_events (tenant_id, ticket_id, event_type, actor_type, actor_admin_id, from_value, to_value)
    values (v_ticket.tenant_id, v_ticket.id, 'category_changed', 'lepefy', p_actor_admin_id, v_ticket.category, p_category);
    v_changed := v_changed + 1;
  end if;

  if v_title is not null and v_title <> v_ticket.title then
    update public.support_tickets set title = v_title where id = v_ticket.id;
    insert into public.support_events (tenant_id, ticket_id, event_type, actor_type, actor_admin_id)
    values (v_ticket.tenant_id, v_ticket.id, 'title_changed', 'lepefy', p_actor_admin_id);
    v_changed := v_changed + 1;
  end if;

  if p_visible is not null and p_visible <> v_ticket.visible_to_tenant then
    update public.support_tickets set visible_to_tenant = p_visible,
      last_public_update_at = case when p_visible then clock_timestamp() else last_public_update_at end
    where id = v_ticket.id;
    insert into public.support_events (tenant_id, ticket_id, event_type, actor_type, actor_admin_id, from_value, to_value)
    values (v_ticket.tenant_id, v_ticket.id, 'visibility_changed', 'lepefy', p_actor_admin_id,
            v_ticket.visible_to_tenant::text, p_visible::text);
    v_changed := v_changed + 1;
  end if;

  if v_changed > 0 then
    update public.support_tickets set updated_at = now() where id = v_ticket.id;
  end if;
  return query select v_changed;
end $$;

-- ─── 14. « Est-ce que le problème est résolu ? » (boutique) ─────────────────
create or replace function public.support_record_feedback(
  p_ticket_id      uuid,
  p_tenant_id      uuid,
  p_actor_admin_id uuid,
  p_solved         boolean
)
returns table (out_status text, out_changed boolean)
language plpgsql security definer set search_path = public as $$
declare
  v_ticket public.support_tickets%rowtype;
  v_to     text;
  v_answer text;
begin
  if p_ticket_id is null or p_tenant_id is null or p_actor_admin_id is null or p_solved is null then
    raise exception 'support_invalid_input';
  end if;
  select * into v_ticket from public.support_tickets where id = p_ticket_id for update;
  if not found or v_ticket.tenant_id <> p_tenant_id or not v_ticket.visible_to_tenant then
    raise exception 'support_ticket_not_found';
  end if;
  v_to := case when p_solved then 'closed' else 'in_progress' end;
  v_answer := case when p_solved then 'solved' else 'not_solved' end;
  -- Double clic : même réponse déjà enregistrée.
  if v_ticket.tenant_feedback = v_answer and v_ticket.status = v_to then
    return query select v_ticket.status, false;
    return;
  end if;
  if v_ticket.status <> 'resolved' then raise exception 'support_feedback_not_expected'; end if;

  update public.support_tickets set
    status = v_to,
    tenant_feedback = case when p_solved then 'solved' else 'not_solved' end,
    tenant_feedback_at = now(),
    closed_at = case when p_solved then now() else closed_at end,
    resolved_at = case when p_solved then resolved_at else null end,
    reopened_at = case when p_solved then reopened_at else now() end,
    reopen_count = reopen_count + case when p_solved then 0 else 1 end,
    last_tenant_message_at = case when p_solved then last_tenant_message_at else now() end,
    last_activity_at = now(),
    updated_at = now()
  where id = v_ticket.id;

  insert into public.support_events (tenant_id, ticket_id, event_type, actor_type, actor_admin_id, from_value, to_value, public)
  values (v_ticket.tenant_id, v_ticket.id, 'tenant_feedback', 'tenant', p_actor_admin_id, v_ticket.status,
          case when p_solved then 'solved' else 'not_solved' end, true);
  if not p_solved then
    insert into public.support_events (tenant_id, ticket_id, event_type, actor_type, actor_admin_id, from_value, to_value, public)
    values (v_ticket.tenant_id, v_ticket.id, 'reopened', 'tenant', p_actor_admin_id, v_ticket.status, v_to, true);
  end if;

  perform public.audit_emit(false, v_ticket.tenant_id, 'support.ticket.status_changed', 'support_ticket', v_ticket.id::text,
    'Demande n° ' || v_ticket.number,
    jsonb_build_array(jsonb_build_object('field', 'status', 'before', v_ticket.status, 'after', v_to)),
    jsonb_build_object('reason', case when p_solved then 'tenant_confirmed' else 'tenant_reopened' end));

  return query select v_to, true;
end $$;

