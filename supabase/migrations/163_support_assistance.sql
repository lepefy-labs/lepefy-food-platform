-- ─── 18. Lectures boutique (projection publique uniquement) ──────────────────
create or replace function public.support_tenant_ticket_page(
  p_tenant_id uuid, p_admin_id uuid, p_view text, p_search text, p_offset integer, p_limit integer
)
returns table (
  id uuid, number bigint, title text, category text, tenant_status text, created_at timestamptz,
  last_activity_at timestamptz, unread boolean, last_message_author text, last_message_excerpt text,
  merged_into_number bigint, total bigint
)
language sql stable security definer set search_path = public as $$
  with base as (
    select t.*, (t.last_public_update_at > coalesce(r.last_read_at, '-infinity'::timestamptz)
                 and (t.last_staff_reply_at is not null or t.status <> 'new') and t.status <> 'closed') as is_unread
    from public.support_tickets t
    left join public.support_read_states r on r.ticket_id = t.id and r.admin_id = p_admin_id
    where t.tenant_id = p_tenant_id and t.visible_to_tenant
      and case when p_view = 'done' then t.status in ('resolved', 'closed') else t.status not in ('resolved', 'closed') end
      and (
        coalesce(btrim(p_search), '') = ''
        or t.number::text = btrim(p_search)
        or t.title ilike '%' || replace(replace(replace(btrim(p_search), '\', '\\'), '%', '\%'), '_', '\_') || '%'
        or t.summary ilike '%' || replace(replace(replace(btrim(p_search), '\', '\\'), '%', '\%'), '_', '\_') || '%'
      )
  )
  select b.id, b.number, b.title, b.category, public.support_tenant_status(b.status), b.created_at, b.last_activity_at, b.is_unread,
         m.author_type, left(m.body, 160), mt.number, count(*) over ()
  from base b
  left join lateral (
    select sm.author_type, sm.body from public.support_messages sm
    where sm.ticket_id = b.id and sm.kind = 'message'
    order by sm.created_at desc limit 1
  ) m on true
  left join public.support_tickets mt on mt.id = b.merged_into_ticket_id and mt.visible_to_tenant
  order by b.is_unread desc, b.last_activity_at desc
  offset greatest(coalesce(p_offset, 0), 0)
  limit least(greatest(coalesce(p_limit, 20), 1), 50)
$$;

create or replace function public.support_tenant_thread(p_tenant_id uuid, p_ticket_id uuid, p_admin_id uuid)
returns jsonb
language sql stable security definer set search_path = public as $$
  select case when t.id is null then null else jsonb_build_object(
    'ticket', jsonb_build_object(
      'id', t.id, 'number', t.number, 'title', t.title, 'category', t.category,
      'tenant_status', public.support_tenant_status(t.status), 'status_detail', case when t.status = 'resolved' then 'resolved' else null end,
      'source_channel', t.source_channel, 'origin', t.origin, 'created_at', t.created_at, 'reported_at', t.reported_at,
      'last_activity_at', t.last_activity_at, 'page_label', t.context->>'page_label', 'resource_label', t.resource_label,
      'tenant_feedback', t.tenant_feedback,
      'merged_into_number', (select mt.number from public.support_tickets mt where mt.id = t.merged_into_ticket_id and mt.visible_to_tenant),
      'last_read_at', (select r.last_read_at from public.support_read_states r where r.ticket_id = t.id and r.admin_id = p_admin_id)
    ),
    'messages', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', m.id, 'author_type', m.author_type, 'author_label', case when m.author_type = 'lepefy' then null else m.author_label end,
        'mine', m.author_admin_id = p_admin_id, 'body', m.body, 'relayed_from', m.relayed_from,
        'original_sent_at', m.original_sent_at, 'created_at', m.created_at,
        'attachments', coalesce((
          select jsonb_agg(jsonb_build_object('id', a.id, 'mime_type', a.mime_type, 'width', a.width, 'height', a.height) order by a.created_at)
          from public.support_attachments a where a.message_id = m.id and not a.internal
        ), '[]'::jsonb)
      ) order by m.created_at)
      from public.support_messages m where m.ticket_id = t.id and m.kind = 'message'
    ), '[]'::jsonb),
    'events', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', e.id, 'event_type', e.event_type, 'created_at', e.created_at,
        'to_tenant_status', case when e.event_type in ('status_changed', 'reopened') then public.support_tenant_status(e.to_value) else null end,
        'value', case when e.event_type in ('merged_into', 'merged_from', 'tenant_feedback', 'imported', 'created') then e.to_value else null end
      ) order by e.created_at)
      from public.support_events e where e.ticket_id = t.id and e.public
    ), '[]'::jsonb)
  ) end
  from (select 1) one
  left join public.support_tickets t on t.id = p_ticket_id and t.tenant_id = p_tenant_id and t.visible_to_tenant
$$;

-- Demandes ouvertes semblables de la MÊME boutique (aucune autre boutique, jamais).
create or replace function public.support_similar_tickets(p_tenant_id uuid, p_text text, p_limit integer default 3)
returns table (id uuid, number bigint, title text, tenant_status text, matches integer)
language plpgsql stable security definer set search_path = public as $$
declare
  v_lexemes text[];
  v_needed  integer;
begin
  if p_tenant_id is null or char_length(coalesce(p_text, '')) < 12 then return; end if;
  v_lexemes := tsvector_to_array(to_tsvector('french'::regconfig, left(p_text, 1000)));
  v_lexemes := array(select l from unnest(v_lexemes) l where char_length(l) >= 3 limit 40);
  if cardinality(v_lexemes) < 2 then return; end if;
  v_needed := greatest(2, ceil(least(cardinality(v_lexemes), 6) * 0.4)::integer);
  return query
    select t.id, t.number, t.title, public.support_tenant_status(t.status), s.n
    from public.support_tickets t
    cross join lateral (
      select count(*)::integer as n from unnest(tsvector_to_array(t.search_document)) l where l = any(v_lexemes)
    ) s
    where t.tenant_id = p_tenant_id and t.visible_to_tenant and t.merged_into_ticket_id is null
      and t.status not in ('resolved', 'closed')
      and t.search_document @@ to_tsquery('simple'::regconfig, array_to_string(array(select quote_literal(l) from unnest(v_lexemes) l), ' | '))
      and s.n >= v_needed
    order by s.n desc, t.last_activity_at desc
    limit least(greatest(coalesce(p_limit, 3), 1), 5);
end $$;

-- ─── 19. File de la console Lepefy (lecture service role) ────────────────────
create or replace view public.support_ticket_queue with (security_invoker = true) as
select
  t.*,
  tn.name as tenant_name,
  tn.slug as tenant_slug,
  q.awaiting_lepefy,
  (q.awaiting_lepefy and coalesce(t.last_tenant_message_at, t.created_at) < now() - interval '24 hours') as stale,
  case
    when t.status in ('resolved', 'closed') then 6
    when q.awaiting_lepefy and t.priority in ('critical', 'high') then 0
    when t.status = 'new' then 1
    when q.awaiting_lepefy and coalesce(t.last_tenant_message_at, t.created_at) < now() - interval '24 hours' then 2
    when q.awaiting_lepefy then 3
    when t.status = 'waiting_tenant' then 5
    else 4
  end as attention_rank
from public.support_tickets t
join public.tenants tn on tn.id = t.tenant_id
cross join lateral (
  select (t.status not in ('waiting_tenant', 'resolved', 'closed') and t.merged_into_ticket_id is null
          and (t.last_staff_reply_at is null or coalesce(t.last_tenant_message_at, t.created_at) > t.last_staff_reply_at)) as awaiting_lepefy
) q;

revoke all on public.support_ticket_queue from public, anon, authenticated;
grant select on public.support_ticket_queue to service_role;

