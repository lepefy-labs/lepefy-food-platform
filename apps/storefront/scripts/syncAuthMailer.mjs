// Copies src/lib/authMailer/core (single source of truth, tested in the
// storefront) into supabase/functions/_shared/authMailer for the Deno Edge
// Function, adding the `.ts` extension Deno requires on relative imports.
//   node scripts/syncAuthMailer.mjs          write
//   node scripts/syncAuthMailer.mjs --check  fail if the copy is stale
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '..', 'src', 'lib', 'authMailer', 'core');
const DEST = join(here, '..', '..', '..', 'supabase', 'functions', '_shared', 'authMailer');
const HEADER = '// GENERATED by apps/storefront/scripts/syncAuthMailer.mjs from src/lib/authMailer/core. Do not edit.\n';

export function transform(source) {
  return HEADER + source.replace(/(from\s+')(\.\/[\w-]+)(')/g, '$1$2.ts$3');
}

const check = process.argv.includes('--check');
let stale = 0;
mkdirSync(DEST, { recursive: true });
for (const file of readdirSync(SRC).filter((f) => f.endsWith('.ts'))) {
  const out = transform(readFileSync(join(SRC, file), 'utf8'));
  const target = join(DEST, file);
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (current === out) continue;
  if (check) { console.error(`stale: ${file}`); stale++; } else writeFileSync(target, out);
}
if (check && stale) process.exit(1);
